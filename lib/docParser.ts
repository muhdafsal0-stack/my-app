// Pure rule-based document & text hierarchy parser
// Complies strictly with zero-AI, 100% client-side rule-based logic.

export interface ParsedItem {
  id: string
  text: string
  level: number // 0 = category, 1 = subcategory, 2 = task
  rawIndex: number
}

export interface PreviewTask {
  id: string
  text: string
}

export interface PreviewSubcategory {
  id: string
  name: string
  tasks: PreviewTask[]
}

export interface PreviewCategory {
  id: string
  name: string
  color: string
  subs: PreviewSubcategory[]
}

export interface ParseOptions {
  tasksPerSubcategory?: number // Default: 3 or 4
  defaultCategoryName?: string
  defaultSubcategoryName?: string
}

const DEFAULT_COLORS = [
  '#E0A030', // Amber
  '#5FB3A5', // Teal
  '#8E86E8', // Indigo
  '#E27D8E', // Rose
  '#6FA0E8', // Sky
  '#A9C25A', // Lime
]

function makeId(): string {
  return Math.random().toString(36).slice(2, 9) + Date.now().toString(36)
}

/**
 * Extracts plain text and semantic structure from an HTML string generated by mammoth or rich text.
 */
export function extractFromHtml(html: string): string[] {
  // Standardize common HTML tags to markdown-like hints
  const formatted = html
    .replace(/<h1[^>]*>([\s\S]*?)<\/h1>/gi, '\n# $1\n')
    .replace(/<h2[^>]*>([\s\S]*?)<\/h2>/gi, '\n## $1\n')
    .replace(/<h3[^>]*>([\s\S]*?)<\/h3>/gi, '\n### $1\n')
    .replace(/<h[4-6][^>]*>([\s\S]*?)<\/h[4-6]>/gi, '\n### $1\n')
    .replace(/<li[^>]*>([\s\S]*?)<\/li>/gi, '\n- $1\n')
    .replace(/<p[^>]*><strong>([\s\S]*?)<\/strong><\/p>/gi, '\n## $1\n')
    .replace(/<p[^>]*>([\s\S]*?)<\/p>/gi, '\n$1\n')
    .replace(/<br\s*\/?>/gi, '\n')
    .replace(/<[^>]+>/g, '') // Strip remaining HTML tags
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')

  return formatted
    .split(/\r?\n/)
    .map(l => l.trim())
    .filter(l => l.length > 0)
}

interface RawLine {
  text: string
  original: string
  indent: number
  explicitLevel: number | null // 0, 1, 2
  isBullet: boolean
  isNumbered: boolean
  prefix?: string
}

/**
 * Parses raw text lines into structured line tokens.
 */
function tokenizeLine(line: string): RawLine | null {
  const trimmed = line.trim()
  if (!trimmed) return null

  // Measure leading spaces or tabs
  let indent = 0
  const matchSpaces = line.match(/^(\s+)/)
  if (matchSpaces) {
    indent = matchSpaces[1].replace(/\t/g, '    ').length
  }

  let text = trimmed
  let explicitLevel: number | null = null
  let isBullet = false
  let isNumbered = false

  // 1. Check Markdown Headings
  if (/^#\s+/.test(text)) {
    explicitLevel = 0
    text = text.replace(/^#\s+/, '')
  } else if (/^##\s+/.test(text)) {
    explicitLevel = 1
    text = text.replace(/^##\s+/, '')
  } else if (/^###+\s+/.test(text)) {
    explicitLevel = 2
    text = text.replace(/^###+\s+/, '')
  }
  // 2. Check explicit keywords like "Category:", "Subcategory:", "Task:"
  else if (/^(Category|Main Category|Module|Unit|Section|Chapter)\s*[:\-–]\s*/i.test(text)) {
    explicitLevel = 0
    text = text.replace(/^(Category|Main Category|Module|Unit|Section|Chapter)\s*[:\-–]\s*/i, '')
  } else if (/^(Subcategory|Sub-category|Topic|Subtopic|Phase|Part)\s*[:\-–]\s*/i.test(text)) {
    explicitLevel = 1
    text = text.replace(/^(Subcategory|Sub-category|Topic|Subtopic|Phase|Part)\s*[:\-–]\s*/i, '')
  } else if (/^(Task|Activity|Item)\s*[:\-–]\s*/i.test(text)) {
    explicitLevel = 2
    text = text.replace(/^(Task|Activity|Item)\s*[:\-–]\s*/i, '')
  }
  // 3. Check outline numbering (e.g. 1. , 1.1 , 1.1.1)
  else if (/^\d+\.\d+\.\d+\.?\s+/.test(text)) {
    explicitLevel = 2
    text = text.replace(/^\d+\.\d+\.\d+\.?\s+/, '')
  } else if (/^\d+\.\d+\.?\s+/.test(text)) {
    explicitLevel = 1
    text = text.replace(/^\d+\.\d+\.?\s+/, '')
  } else if (/^\d+\.\s+/.test(text)) {
    isNumbered = true
    // Single number "1. " could be a category, subcategory, or task depending on indent
    if (indent === 0) explicitLevel = 0
    else if (indent <= 4) explicitLevel = 1
    else explicitLevel = 2
    text = text.replace(/^\d+\.\s+/, '')
  }
  // 4. Roman numerals: I. II. III.
  else if (/^(I|II|III|IV|V|VI|VII|VIII|IX|X)\.\s+/i.test(text)) {
    explicitLevel = 0
    text = text.replace(/^(I|II|III|IV|V|VI|VII|VIII|IX|X)\.\s+/i, '')
  }
  // 5. Letter numbering: A. B. C. or a. b. c.
  else if (/^[A-Z]\.\s+/.test(text)) {
    explicitLevel = 1
    text = text.replace(/^[A-Z]\.\s+/, '')
  } else if (/^[a-z]\.\s+/.test(text)) {
    explicitLevel = 2
    text = text.replace(/^[a-z]\.\s+/, '')
  }
  // 6. Bullets: -, *, •, +, –, —
  else if (/^[-*•+–—]\s+/.test(text)) {
    isBullet = true
    text = text.replace(/^[-*•+–—]\s+/, '')
    if (indent === 0) {
      // Top level bullet
      explicitLevel = 2 // usually a task if bulleted
    } else if (indent <= 4) {
      explicitLevel = 2
    } else {
      explicitLevel = 2
    }
  }

  // Check for common prefix delimiter in text, e.g. "Mathematics: Calculus" or "Workout - Arms"
  let prefix: string | undefined
  const delimMatch = text.match(/^([A-Za-z0-9\s]{2,25})\s*[:|\-–]\s+(.+)$/)
  if (delimMatch && delimMatch[1].length < 25) {
    prefix = delimMatch[1].trim()
  }

  return {
    text: text.trim(),
    original: trimmed,
    indent,
    explicitLevel,
    isBullet,
    isNumbered,
    prefix,
  }
}

/**
 * Chunks an array of task texts into subcategories with target 3-4 items each.
 */
function chunkTasks(
  tasks: Array<{ text: string }>,
  baseName: string,
  targetChunkSize = 4
): PreviewSubcategory[] {
  if (tasks.length === 0) {
    return [{ id: makeId(), name: baseName, tasks: [] }]
  }

  // If 4 or fewer tasks, keep them in a single subcategory
  if (tasks.length <= targetChunkSize) {
    return [
      {
        id: makeId(),
        name: baseName,
        tasks: tasks.map(t => ({ id: makeId(), text: t.text })),
      },
    ]
  }

  // Split into chunks of 3–4 tasks
  const result: PreviewSubcategory[] = []
  const total = tasks.length
  // Calculate optimal chunk size between 3 and 4
  const numChunks = Math.ceil(total / targetChunkSize)
  const itemsPerChunk = Math.ceil(total / numChunks)

  for (let i = 0; i < total; i += itemsPerChunk) {
    const chunk = tasks.slice(i, i + itemsPerChunk)
    const partNum = Math.floor(i / itemsPerChunk) + 1
    const name = numChunks > 1 ? `${baseName} (Part ${partNum})` : baseName
    result.push({
      id: makeId(),
      name,
      tasks: chunk.map(t => ({ id: makeId(), text: t.text })),
    })
  }

  return result
}

/**
 * Main Rule-Based Hierarchy Organizer
 */
export function organizeContent(
  lines: string[],
  options: ParseOptions = {}
): PreviewCategory[] {
  const targetChunk = options.tasksPerSubcategory || 4
  const defaultCatName = options.defaultCategoryName || 'General'
  const defaultSubName = options.defaultSubcategoryName || 'Tasks'

  // Step 1: Tokenize all lines
  const tokens: RawLine[] = []
  for (const line of lines) {
    const tok = tokenizeLine(line)
    if (tok && tok.text) tokens.push(tok)
  }

  if (tokens.length === 0) return []

  // Step 2: Determine if content has explicit hierarchical structure
  const hasHeadings = tokens.some(t => t.explicitLevel === 0 || t.explicitLevel === 1)
  const hasIndents = tokens.some(t => t.indent > 0)
  const isStructured = hasHeadings || hasIndents

  let categories: PreviewCategory[] = []

  if (isStructured) {
    // Hierarchical parsing state machine
    let currentCat: { name: string; subs: Array<{ name: string; tasks: string[] }> } | null = null
    let currentSub: { name: string; tasks: string[] } | null = null

    const ensureCategory = (name = defaultCatName) => {
      if (!currentCat) {
        currentCat = { name, subs: [] }
      }
      return currentCat
    }

    const ensureSubcategory = (name = defaultSubName) => {
      const cat = ensureCategory()
      if (!currentSub) {
        currentSub = { name, tasks: [] }
        cat.subs.push(currentSub)
      }
      return currentSub
    }

    for (let i = 0; i < tokens.length; i++) {
      const tok = tokens[i]

      // Determine level based on explicit level, indentation, or token context
      let level: number
      if (tok.explicitLevel !== null) {
        level = tok.explicitLevel
      } else if (tok.indent === 0 && !tok.isBullet) {
        // Look ahead: if next tokens are indented or bulleted, this is a header
        const next = tokens[i + 1]
        if (next && (next.indent > 0 || next.isBullet)) {
          level = currentCat === null ? 0 : 1
        } else {
          level = 2
        }
      } else if (tok.indent > 0 && tok.indent <= 4) {
        level = 1
      } else {
        level = 2
      }

      if (level === 0) {
        // New Category
        if (currentCat) {
          // Commit previous
          categories.push(buildCategory(currentCat, categories.length, targetChunk))
        }
        currentCat = { name: tok.text, subs: [] }
        currentSub = null
      } else if (level === 1) {
        // New Subcategory
        const cat = ensureCategory()
        currentSub = { name: tok.text, tasks: [] }
        cat.subs.push(currentSub)
      } else {
        // Task
        const sub = ensureSubcategory()
        sub.tasks.push(tok.text)
      }
    }

    if (currentCat) {
      categories.push(buildCategory(currentCat, categories.length, targetChunk))
    }
  } else {
    // Unstructured flat list of tasks / topics!
    categories = organizeUnstructured(tokens, defaultCatName, defaultSubName, targetChunk)
  }

  // Ensure no category has 0 subcategories and no tasks are omitted
  return categories.filter(c => c.subs.some(s => s.tasks.length > 0))
}

function buildCategory(
  rawCat: { name: string; subs: Array<{ name: string; tasks: string[] }> },
  colorIndex: number,
  targetChunk: number
): PreviewCategory {
  const catColor = DEFAULT_COLORS[colorIndex % DEFAULT_COLORS.length]
  const finalSubs: PreviewSubcategory[] = []

  for (const s of rawCat.subs) {
    if (s.tasks.length > targetChunk + 1) {
      // Main category or subcategory contains many items -> divide into 3-4 tasks each
      const chunked = chunkTasks(
        s.tasks.map(t => ({ text: t })),
        s.name,
        targetChunk
      )
      finalSubs.push(...chunked)
    } else if (s.tasks.length > 0) {
      finalSubs.push({
        id: makeId(),
        name: s.name,
        tasks: s.tasks.map(t => ({ id: makeId(), text: t })),
      })
    }
  }

  // If subcategories were empty but tasks existed, handle gracefully
  if (finalSubs.length === 0) {
    finalSubs.push({
      id: makeId(),
      name: 'General',
      tasks: [],
    })
  }

  return {
    id: makeId(),
    name: rawCat.name,
    color: catColor,
    subs: finalSubs,
  }
}

/**
 * Organizes completely unstructured items logically by detecting common prefixes or chunking.
 */
function organizeUnstructured(
  tokens: RawLine[],
  defaultCatName: string,
  defaultSubName: string,
  targetChunk: number
): PreviewCategory[] {
  // Check if items have common prefixes (e.g. "Math: Calculus", "Math: Algebra")
  const prefixGroups = new Map<string, string[]>()
  const flatTasks: string[] = []

  for (const t of tokens) {
    if (t.prefix) {
      const list = prefixGroups.get(t.prefix) || []
      // Remove prefix from text for cleaner display
      const cleanText = t.text.replace(new RegExp(`^${escapeRegex(t.prefix)}\\s*[:|\\-–]\\s*`), '').trim()
      list.push(cleanText || t.text)
      prefixGroups.set(t.prefix, list)
    } else {
      flatTasks.push(t.text)
    }
  }

  // If prefix groups cover at least 40% of items, use prefix clustering
  if (prefixGroups.size >= 2 && Array.from(prefixGroups.values()).reduce((a, b) => a + b.length, 0) >= tokens.length * 0.4) {
    const cats: PreviewCategory[] = []
    let colorIdx = 0

    prefixGroups.forEach((tasks, prefix) => {
      const subs = chunkTasks(
        tasks.map(t => ({ text: t })),
        'Tasks',
        targetChunk
      )
      cats.push({
        id: makeId(),
        name: prefix,
        color: DEFAULT_COLORS[colorIdx++ % DEFAULT_COLORS.length],
        subs,
      })
    })

    if (flatTasks.length > 0) {
      const subs = chunkTasks(
        flatTasks.map(t => ({ text: t })),
        defaultSubName,
        targetChunk
      )
      cats.push({
        id: makeId(),
        name: defaultCatName,
        color: DEFAULT_COLORS[colorIdx++ % DEFAULT_COLORS.length],
        subs,
      })
    }

    return cats
  }

  // Otherwise, group flat list of tasks into categories and subcategories of 3-4 tasks
  const totalTasks = tokens.map(t => t.text)
  const MAX_TASKS_PER_CATEGORY = targetChunk * 3 // e.g. 12 tasks per category max

  if (totalTasks.length <= MAX_TASKS_PER_CATEGORY) {
    // 1 Category with multiple subcategories of 3-4 tasks
    const subs = chunkTasks(
      totalTasks.map(t => ({ text: t })),
      defaultSubName,
      targetChunk
    )
    return [
      {
        id: makeId(),
        name: defaultCatName,
        color: DEFAULT_COLORS[0],
        subs,
      },
    ]
  }

  // Multiple categories
  const categories: PreviewCategory[] = []
  let colorIdx = 0
  for (let i = 0; i < totalTasks.length; i += MAX_TASKS_PER_CATEGORY) {
    const slice = totalTasks.slice(i, i + MAX_TASKS_PER_CATEGORY)
    const catNum = Math.floor(i / MAX_TASKS_PER_CATEGORY) + 1
    const subs = chunkTasks(
      slice.map(t => ({ text: t })),
      `Group`,
      targetChunk
    )
    categories.push({
      id: makeId(),
      name: `${defaultCatName} (Section ${catNum})`,
      color: DEFAULT_COLORS[colorIdx++ % DEFAULT_COLORS.length],
      subs,
    })
  }

  return categories
}

function escapeRegex(str: string): string {
  return str.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}
